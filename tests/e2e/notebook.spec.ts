import { expect, test } from '@playwright/test'

test('变量、矩阵、历史、重载、主题与键盘操作', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  const input = page.getByLabel('开始计算')
  await expect(input).toBeFocused()
  await page.screenshot({ path: 'test-results/empty-light.png', fullPage: true })
  for (const expression of ['price = 128', 'price * 3', 'A = [1, 2; 3, 4]', 'inv(A)']) {
    await input.fill(expression)
    await input.press('Enter')
    await expect(page.getByRole('button', { name: '计算', exact: true })).toBeEnabled()
    await expect(page.locator('.history-card').first().locator('.entry-expression')).toContainText(expression)
  }
  await expect(page.locator('.history-card')).toHaveCount(4)
  await expect(page.locator('.history-card').first().locator('.formula')).toHaveAttribute('aria-label', '[-2, 1; 1.5, -0.5]')
  await page.screenshot({ path: 'test-results/notebook-light.png', fullPage: true })
  await page.reload()
  await expect(page.locator('.history-card')).toHaveCount(4)
  await input.fill('price + 2')
  await input.press('Enter')
  await expect(page.locator('.history-card').first().locator('.formula')).toHaveAttribute('aria-label', '130')
  await page.getByLabel('外观主题').selectOption('dark')
  await page.screenshot({ path: 'test-results/notebook-dark.png', fullPage: true })
  await input.press('Control+k')
  await expect(page.getByLabel('搜索历史')).toBeFocused()
  await page.getByLabel('搜索历史').fill('384')
  await expect(page.locator('.history-card')).toHaveCount(1)
  await page.getByLabel('搜索历史').fill('')
  await input.fill('0.1 + 0.2')
  await input.dispatchEvent('keydown', { key: 'Enter', isComposing: true })
  await expect(page.locator('.history-card')).toHaveCount(5)
  await input.press('Enter')
  await expect(page.locator('.history-card').first().locator('.formula')).toHaveAttribute('aria-label', '0.3')
  await input.fill('1 / 0')
  await input.press('Enter')
  await expect(page.getByRole('alert')).toBeVisible()
  await expect(page.locator('.history-card')).toHaveCount(6)
  await page.setViewportSize({ width: 375, height: 812 })
  await page.screenshot({ path: 'test-results/notebook-mobile.png', fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  expect(errors).toEqual([])
})

test('删除与撤销、清空确认、变量仍保留', async ({ page }) => {
  await page.goto('/')
  const input = page.getByLabel('开始计算')
  await input.fill('x = 7')
  await expect(page.getByRole('button', { name: '计算', exact: true })).toBeEnabled()
  await input.press('Enter')
  await expect(page.locator('.history-card')).toHaveCount(1)
  await page.getByRole('button', { name: '删除记录 x = 7', exact: true }).click()
  await expect(page.locator('.history-card')).toHaveCount(0)
  await page.getByRole('button', { name: '撤销删除' }).click()
  await expect(page.locator('.history-card')).toHaveCount(1)
  await page.getByRole('button', { name: '清空', exact: true }).click()
  await page.getByRole('button', { name: '取消', exact: true }).click()
  await expect(page.locator('.history-card')).toHaveCount(1)
  await page.getByRole('button', { name: '清空', exact: true }).click()
  await page.getByRole('button', { name: '确认清空', exact: true }).click()
  await expect(page.locator('.history-card')).toHaveCount(0)
  await input.fill('x + 1')
  await input.press('Enter')
  await expect(page.locator('.history-card').first().locator('.formula')).toHaveAttribute('aria-label', '8')
})
